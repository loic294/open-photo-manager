# shellcheck shell=bash
# manifest.json and its companions. Sourced by generate.sh after common.sh.
#
# Needs OUT, WORK, SCALE, FILES, SIG and EXH. The heavy lifting (joining the catalogue registry with the measured
# tree and cross-checking links, duplicate groups and scenarios) is manifest.awk; this file only gathers the inputs
# and stitches the pieces into one JSON document. No jq or python: the scripts also run in the Debian image.

# manifest_json_escape STRING : JSON string body in FX_R (quotes, backslashes and control characters).
manifest_json_escape() {
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  s=${s//$'\t'/\\t}
  s=${s//$'\n'/\\n}
  FX_R=$s
}

# manifest_tool_versions : V_EXIFTOOL, V_FFMPEG, V_VIPS and V_HEIF (the tools decide the bytes of the generated media).
manifest_tool_versions() {
  V_EXIFTOOL=$(exiftool -ver 2>/dev/null | awk 'NR == 1 { v = $1 } END { print v }') || true
  V_FFMPEG=$(ffmpeg -version 2>/dev/null | awk 'NR == 1 { v = $3 } END { print v }') || true
  V_VIPS=$(vips --version 2>/dev/null | awk 'NR == 1 { v = $1 } END { print v }') || true
  V_HEIF=none
  if command -v heif-enc >/dev/null 2>&1; then
    V_HEIF=$(heif-enc --version 2>&1 | awk 'NR == 1 { v = $NF } END { print v }') || true
  fi
  : "${V_EXIFTOOL:=unknown}" "${V_FFMPEG:=unknown}" "${V_VIPS:=unknown}" "${V_HEIF:=unknown}"
}

# manifest_readme : OUT/README.txt, a pointer plus the scenario list.
manifest_readme() {
  {
    printf '%s\n' "Fixture photo library generated by fixtures/generate.sh (scale: $SCALE, $1 files and symlinks)."
    printf '%s\n' "Point APM_VOLUMES_DIR at ./volumes. manifest.json lists every file with its expected values;"
    printf '%s\n' "manifest.tsv, manifest.dirs.tsv and manifest.dups.tsv are flat versions of the same data."
    printf '%s\n' "Documentation: fixtures/README.md"
    printf '\n%s\n' "Scenarios (key, then description):"
    awk -F '\t' '{ printf "  %-34s %s\n", $1, $3 }' "$WORK/scenarios.tsv"
    if [ -s "$WORK/skipped.tsv" ]; then
      printf '\n%s\n' "Skipped on this machine:"
      awk -F '\t' '{ printf "  %-34s %s\n", $1, $2 }' "$WORK/skipped.tsv"
    fi
  } >"$OUT/README.txt"
}

# manifest_build : writes manifest.json, manifest.tsv, manifest.dirs.tsv, manifest.dups.tsv and README.txt into OUT.
manifest_build() {
  local p="$WORK/m" sorted="$WORK/reg.sorted.tsv" summary m sep f outside
  fx_collect_meta "$OUT" "$WORK/stat.tsv" "$WORK/sha.tsv" photos archive
  (cd "$OUT/volumes" && find photos archive -type d | sort) >"$WORK/dirs.list"
  sort -t $'\t' -k1,1 -k2,2 "$WORK/reg.tsv" >"$sorted"

  if ! summary=$(awk -v F_STAT="$WORK/stat.tsv" -v F_SHA="$WORK/sha.tsv" -v F_REG="$sorted" -v F_LINKS="$WORK/links.tsv" \
    -v F_GRP="$WORK/dupgroups.tsv" -v F_DUPS="$WORK/dups.tsv" -v F_DIRSCN="$WORK/dirscn.tsv" -v F_SCN="$WORK/scenarios.tsv" \
    -v F_SKIP="$WORK/skipped.tsv" -v F_DIRS="$WORK/dirs.list" -v O="$p" -v EXH="$EXH" \
    -f "$FX_LIB_DIR/manifest.awk" "$WORK/stat.tsv" "$WORK/sha.tsv" "$sorted" "$WORK/links.tsv" "$WORK/dupgroups.tsv" \
    "$WORK/dups.tsv" "$WORK/dirscn.tsv" "$WORK/scenarios.tsv" "$WORK/skipped.tsv" "$WORK/dirs.list"); then
    fx_die "the generated tree does not match the catalogue (see the assertions above)"
  fi
  fx_log "manifest: $summary"

  manifest_tool_versions
  outside=''
  if [ -d "$OUT/outside" ]; then
    sep=''
    while IFS= read -r f; do
      manifest_json_escape "$f"
      outside="$outside$sep\"$FX_R\""
      sep=,
    done < <(cd "$OUT" && find outside -type f | sort)
  fi

  {
    printf '{\n"schema_version":1,\n'
    printf '"generator":{"scale":"%s","entries":%s,"signature":"%s","tz_assumed":"UTC","tools":{"exiftool":"%s","ffmpeg":"%s","vips":"%s","heif_enc":"%s"}},\n' \
      "$SCALE" "$(awk 'END { print NR }' "$p.tsv")" "$SIG" "$V_EXIFTOOL" "$V_FFMPEG" "$V_VIPS" "$V_HEIF"
    printf '"volumes_dir":"volumes",\n"volumes":["photos","archive"],\n'
    printf '"counters":'
    cat "$p.counters.json"
    printf ',\n"scenarios":{\n'
    cat "$p.scn.json"
    printf '\n},\n"duplicate_groups":{'
    sep=''
    for m in 1 2 3 4 multi none; do
      case $m in
        multi | none) printf '%s"%s":[' "$sep" "$m" ;;
        *) printf '%s"mode%s":[' "$sep" "$m" ;;
      esac
      cat "$p.grp.$m"
      printf '\n]'
      sep=,
    done
    printf '},\n"empty_dirs":['
    cat "$p.empty.json"
    printf '\n],\n"non_empty_dirs":['
    cat "$p.nonempty.json"
    printf '\n],\n"outside_files":[%s],\n"skipped":[\n' "$outside"
    cat "$p.skipped.json"
    printf '\n],\n"files":['
    cat "$p.files.json"
    printf '\n]\n}\n'
  } >"$OUT/manifest.json"

  {
    printf '%s\n' '#volume	path	type	size	sha1	mtime	kind	db_kind	scenario	indexable	capture_ts	capture_src	capture_offset_min	camera	rating	flag	tags	skip_reason	link_target'
    cat "$p.tsv"
  } >"$OUT/manifest.tsv"
  {
    printf '%s\n' '#volume	path	state	scenario'
    cat "$p.dirs.tsv"
  } >"$OUT/manifest.dirs.tsv"
  {
    printf '%s\n' '#mode	group	volume	path	role	match	modes	plain_prefix_only'
    cat "$p.dups.tsv"
  } >"$OUT/manifest.dups.tsv"
  manifest_readme "$(awk 'END { print NR }' "$p.tsv")"
}
