#!/usr/bin/env bash
# Deterministic photo-library fixture generator (see fixtures/README.md).
#
#   fixtures/generate.sh [--out DIR] [--scale small|large] [--files N] [--clean] [--clean-only] [--jobs N]
#
# Builds OUT/volumes/{photos,archive} plus manifest.json (and flat TSV companions) describing exactly what was written
# and what the indexer is expected to find. Running it again with the same arguments prints "up to date" and does not
# touch the tree; the tree is rebuilt when the generator, the tools or the arguments changed, when a file was modified
# (for example by mutations.sh) or with --clean.
set -euo pipefail

FX_TAG=generate
# shellcheck source=lib/common.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"
# shellcheck source=lib/media.sh
. "$FX_LIB_DIR/media.sh"
# shellcheck source=lib/small.sh
. "$FX_LIB_DIR/small.sh"
# shellcheck source=lib/bulk.sh
. "$FX_LIB_DIR/bulk.sh"
# shellcheck source=lib/manifest.sh
. "$FX_LIB_DIR/manifest.sh"

usage() {
  printf '%s\n' \
    "Usage: fixtures/generate.sh [options]" \
    "" \
    "Builds a deterministic photo library (volumes/photos and volumes/archive) with manifest.json." \
    "A second run with the same arguments prints 'up to date' and changes nothing." \
    "" \
    "  --out DIR         output directory (default: fixtures/out); only directories made by this tool are replaced" \
    "  --scale small     the scenario catalogue: a few hundred files with real metadata (default)" \
    "  --scale large     tiny generated files for load tests, see --files" \
    "  --files N         number of files at large scale (default 200000, minimum 1000)" \
    "  --clean           regenerate even when the output is up to date" \
    "  --clean-only      remove the output directory and stop" \
    "  --jobs N          parallel file writers at large scale (default: CPU count, at most 8)" \
    "  --no-exhaustive   skip the pairwise duplicate cross-check inside the manifest builder (faster at very large scale)" \
    "  -h, --help        this text"
}

OUT_ARG='' SCALE=small FILES='' CLEAN=0 CLEAN_ONLY=0 JOBS='' EXH=1
while [ $# -gt 0 ]; do
  case $1 in
    --out | --scale | --files | --jobs)
      if [ $# -lt 2 ]; then fx_die "$1 needs a value"; fi
      case $1 in
        --out) OUT_ARG=$2 ;;
        --scale) SCALE=$2 ;;
        --files) FILES=$2 ;;
        --jobs) JOBS=$2 ;;
      esac
      shift 2
      ;;
    --out=*) OUT_ARG=${1#--out=} && shift ;;
    --scale=*) SCALE=${1#--scale=} && shift ;;
    --files=*) FILES=${1#--files=} && shift ;;
    --jobs=*) JOBS=${1#--jobs=} && shift ;;
    --clean) CLEAN=1 && shift ;;
    --clean-only) CLEAN_ONLY=1 && shift ;;
    --no-exhaustive) EXH=0 && shift ;;
    -h | --help)
      usage
      exit 0
      ;;
    *) fx_die "unknown argument '$1' (try --help)" ;;
  esac
done

case $SCALE in
  small)
    if [ -n "$FILES" ]; then fx_die "--files only applies to --scale large"; fi
    FILES=-
    ;;
  large)
    FILES=${FILES:-200000}
    case $FILES in
      '' | *[!0-9]*) fx_die "--files needs a number" ;;
    esac
    if [ "$FILES" -lt 1000 ]; then fx_die "--files must be at least 1000"; fi
    ;;
  *) fx_die "--scale must be small or large" ;;
esac
if [ -z "$JOBS" ]; then
  fx_nproc
  JOBS=$FX_R
  if [ "$JOBS" -gt 8 ]; then JOBS=8; fi
fi
case $JOBS in
  '' | *[!0-9]* | 0) fx_die "--jobs needs a positive number" ;;
esac

fx_abs_path "${OUT_ARG:-$FX_DIR/out}"
OUT=$FX_R
case $OUT in
  *[\\$'\t\n']*) fx_die "the output path must not contain backslashes, tabs or newlines: $OUT" ;;
esac
fx_safe_out "$OUT"
WORK=$OUT/.work
STAGE=$WORK/stage
LOCK=$OUT.lock
HAVE_LOCK=0

on_exit() {
  local rc=$?
  if [ "$HAVE_LOCK" = 1 ]; then rm -rf "$LOCK"; fi
  if [ "$rc" != 0 ] && [ -d "$WORK" ]; then
    fx_warn "generation failed; scratch files stay in $WORK (generate.sh --clean starts over)"
  fi
  return "$rc"
}
trap on_exit EXIT
trap 'exit 130' INT TERM

# One generator at a time per output directory (tests may start several processes that all call make fixtures).
acquire_lock() {
  local waited=0 owner
  mkdir -p "$(dirname "$OUT")"
  while ! mkdir "$LOCK" 2>/dev/null; do
    owner=$(cat "$LOCK/pid" 2>/dev/null || true)
    if [ -n "$owner" ] && ! kill -0 "$owner" 2>/dev/null; then
      rm -rf "$LOCK"
      continue
    fi
    waited=$((waited + 1))
    if [ "$waited" -gt 900 ]; then fx_die "gave up waiting for the generator that holds $LOCK"; fi
    if [ "$waited" = 1 ]; then fx_log "waiting for another generator to finish ($LOCK)"; fi
    sleep 1
  done
  HAVE_LOCK=1
  printf '%s\n' "$$" >"$LOCK/pid"
}

# compute_signature : SIG identifies everything that decides the generated bytes.
compute_signature() {
  manifest_tool_versions
  SIG=$(
    {
      cat "$FX_DIR/generate.sh" "$FX_LIB_DIR"/*
      printf 'scale=%s files=%s exiftool=%s ffmpeg=%s vips=%s heif=%s\n' "$SCALE" "$FILES" "$V_EXIFTOOL" "$V_FFMPEG" "$V_VIPS" "$V_HEIF"
    } | fx_sha1_stdin
  )
}

up_to_date() {
  local stamp="$OUT/.fixtures-stamp"
  if [ ! -f "$stamp" ] || [ ! -f "$OUT/manifest.json" ] || [ -e "$OUT/.mutations-applied" ]; then return 1; fi
  if [ "$(fx_stamp_get "$stamp" sig)" != "$SIG" ]; then return 1; fi
  [ "$(fx_stamp_get "$stamp" tree)" = "$(fx_tree_fingerprint "$OUT")" ]
}

# finish_tree : fixed folder mtimes, the unreadable scenarios (last, so nothing above needs access) and the stamp.
finish_tree() {
  local f tree
  find "$OUT/volumes" "$OUT/outside" -type d -exec env TZ=UTC touch -t 202001010000.00 {} + 2>/dev/null || true
  sort -u "$WORK/unreadable.list" >"$OUT/.fixtures-unreadable"
  if [ -s "$OUT/.fixtures-unreadable" ]; then
    # children first: a folder that is already locked cannot be searched
    while IFS= read -r f; do
      chmod 000 "$OUT/$f"
    done < <(sort -r "$OUT/.fixtures-unreadable")
  fi
  tree=$(fx_tree_fingerprint "$OUT")
  printf 'sig=%s\nscale=%s\nfiles=%s\ntree=%s\n' "$SIG" "$SCALE" "$FILES" "$tree" >"$OUT/.fixtures-stamp"
}

generate() {
  local t0=$SECONDS n
  fx_clean_out "$OUT"
  mkdir -p "$OUT"
  printf '%s\n' "Created by fixtures/generate.sh. Safe to delete; the generator only replaces directories that carry this marker." >"$OUT/.fixtures-owned"
  mkdir -p "$OUT/volumes/photos" "$OUT/volumes/archive" "$STAGE"
  fx_log "generating the $SCALE fixture library in $OUT"
  media_init
  tpl_init
  case $SCALE in
    small) small_catalogue ;;
    large) bulk_plan ;;
  esac
  media_run_exiftool
  media_run_copies
  media_apply_touch "$WORK/touch.tsv"
  manifest_build
  finish_tree
  rm -rf "$WORK"
  n=$(awk 'END { print NR - 1 }' "$OUT/manifest.tsv")
  fx_rate "$n" $((SECONDS - t0)) files
  fx_log "done: $FX_R; manifest at $OUT/manifest.json"
}

fx_detect_portability
if [ "$CLEAN_ONLY" = 1 ]; then
  if [ -e "$OUT" ] || [ -L "$OUT" ]; then
    acquire_lock
    fx_clean_out "$OUT"
    fx_log "removed $OUT"
  else
    fx_log "nothing to remove: $OUT does not exist"
  fi
  exit 0
fi

fx_need exiftool ffmpeg vips awk find xargs sort touch od tr cmp dd cp chmod stat paste cat
compute_signature
acquire_lock
if [ "$CLEAN" = 0 ] && up_to_date; then
  fx_log "up to date: $OUT ($SCALE scale; --clean regenerates)"
  exit 0
fi
generate
